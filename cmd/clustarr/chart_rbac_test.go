package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// The sentinels that bracket the generated block in the chart template. They
// are comments, so Helm passes them through untouched and this test can read
// the block without rendering the chart -- which matters, because the block
// contains no Go template at all and a test that shelled out to helm would
// skip on any machine without it.
const (
	chartRBACBegin = "# BEGIN generated from config/rbac/role.yaml -- do not edit by hand."
	chartRBACEnd   = "# END generated from config/rbac/role.yaml."
)

// TestChartRBACMatchesTheGeneratedRole is the chart-drift gate.
//
// Clustarr ships two installers for one topology: config/ (kustomize) and
// charts/clustarr (Helm). config/rbac/role.yaml is generated by `make
// manifests` from the +kubebuilder:rbac markers; the chart's copy was written
// by hand in M0 and had drifted into something unrelated -- a blanket
// `resources: ["*"]` READ on every Clustarr group and nothing else, so a
// Helm-installed Clustarr could not have written a single status.
//
// Helm cannot read a file outside its own chart directory, so the chart
// cannot template the generated rules at render time: a copy inside the chart
// is unavoidable, whether committed as data or pasted into the template. What
// makes it safe is this test, not the copy's location. It compares the block
// verbatim, so a stale copy fails with a diff rather than with a subtle
// permission gap nobody sees until an operator's pod is denied.
func TestChartRBACMatchesTheGeneratedRole(t *testing.T) {
	root, err := filepath.Abs("../..")
	require.NoError(t, err)

	generated, err := os.ReadFile(filepath.Join(root, "config", "rbac", "role.yaml"))
	require.NoError(t, err)
	_, want, found := strings.Cut(string(generated), "\nrules:\n")
	require.True(t, found, "config/rbac/role.yaml has no rules: block")

	chart, err := os.ReadFile(filepath.Join(root, "charts", "clustarr", "templates", "rbac.yaml"))
	require.NoError(t, err)

	_, after, found := strings.Cut(string(chart), chartRBACBegin+"\n")
	require.True(t, found,
		"charts/clustarr/templates/rbac.yaml no longer carries the %q sentinel; "+
			"either the generated block was removed or the sentinel was renamed without this test", chartRBACBegin)
	got, _, found := strings.Cut(after, chartRBACEnd)
	require.True(t, found, "charts/clustarr/templates/rbac.yaml has no %q sentinel", chartRBACEnd)

	require.Equal(t, strings.TrimRight(want, "\n"), strings.TrimRight(got, "\n"),
		"the Helm chart's manager ClusterRole has drifted from config/rbac/role.yaml.\n"+
			"Run `make manifests`, then copy the rules: list from config/rbac/role.yaml into\n"+
			"charts/clustarr/templates/rbac.yaml between the BEGIN/END sentinels.")
}
